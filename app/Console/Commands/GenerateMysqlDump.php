<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Modules\CRM\Entities\Client;
use Modules\Operations\Entities\Shipment;
use Illuminate\Support\Facades\File;

class GenerateMysqlDump extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'app:generate-mysql-dump';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Generate a MySQL-compatible SQL dump of Clients and Shipments';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $this->info('Generating MySQL dump...');

        $dumpDir = database_path('dumps');
        if (!File::exists($dumpDir)) {
            File::makeDirectory($dumpDir, 0755, true);
        }
        $outputPath = $dumpDir . '/legacy_data.sql';

        $content = "-- MySQL Dump generated by ADGOD-OS\n";
        $content .= "-- Date: " . now()->toDateTimeString() . "\n\n";
        $content .= "SET FOREIGN_KEY_CHECKS=0;\n\n";

        // 1. Dump Clients
        $clients = Client::all();
        $this->info("Dumping " . $clients->count() . " clients...");
        foreach ($clients as $client) {
            $content .= $this->generateInsert('clients', $client->getAttributes());
        }
        $content .= "\n";

        // 2. Dump Shipments
        $shipments = Shipment::all();
        $this->info("Dumping " . $shipments->count() . " shipments...");
        foreach ($shipments as $shipment) {
            $content .= $this->generateInsert('shipments', $shipment->getAttributes());
        }

        $content .= "\nSET FOREIGN_KEY_CHECKS=1;\n";

        File::put($outputPath, $content);

        $this->info("Dump saved to: $outputPath");
        return 0;
    }

    private function generateInsert($table, $attributes)
    {
        // Filter out nulls if you want, but better to keep structure
        // Actually, we must include all columns defined in insert if we specify columns, or all if we don't.
        // Let's rely on array keys for column names.

        $columns = array_keys($attributes);
        $values = array_values($attributes);

        $escapedValues = array_map(function ($value) {
            if (is_null($value)) {
                return 'NULL';
            }
            if (is_bool($value)) {
                return $value ? 1 : 0;
            }
            if (is_numeric($value)) {
                // Keep as is, but be careful with strings that look like numbers but have leading zeros?
                // Safer to quote everything except numbers that are strictly int/float types in PHP, 
                // but database driver usually returns strings.
                // Let's just quote strings and escape special chars.
                return "'" . addslashes((string) $value) . "'";
            }
            // Default string handling
            return "'" . addslashes((string) $value) . "'";
        }, $values);

        $colsStr = '`' . implode('`, `', $columns) . '`';
        $valsStr = implode(', ', $escapedValues);

        return "INSERT INTO `$table` ($colsStr) VALUES ($valsStr);\n";
    }
}
